create table public.bookmark_catalog (
  resource_type text not null check (resource_type in ('guide', 'question')),
  resource_id text not null check (length(resource_id) between 1 and 100),
  primary key (resource_type, resource_id)
);
alter table public.bookmark_catalog enable row level security;
revoke all on public.bookmark_catalog from public, anon, authenticated;
grant select on public.bookmark_catalog to authenticated;
create policy "owner reads published bookmark references" on public.bookmark_catalog
for select to authenticated using ((select private.is_learning_owner()));

create table public.bookmarks (
  user_id uuid not null references auth.users(id) on delete cascade,
  resource_type text not null,
  resource_id text not null,
  saved_at timestamptz not null default now(),
  primary key (user_id, resource_type, resource_id),
  foreign key (resource_type, resource_id) references public.bookmark_catalog(resource_type, resource_id)
);
create index bookmarks_owner_saved on public.bookmarks(user_id, saved_at desc, resource_type, resource_id);
alter table public.bookmarks enable row level security;
revoke all on public.bookmarks from public, anon, authenticated;
grant select, delete on public.bookmarks to authenticated;
grant insert (user_id, resource_type, resource_id) on public.bookmarks to authenticated;
create policy "owner reads bookmarks" on public.bookmarks for select to authenticated
using ((select private.is_learning_owner()) and user_id = (select auth.uid()));
create policy "owner adds bookmarks" on public.bookmarks for insert to authenticated
with check ((select private.is_learning_owner()) and user_id = (select auth.uid()));
create policy "owner removes bookmarks" on public.bookmarks for delete to authenticated
using ((select private.is_learning_owner()) and user_id = (select auth.uid()));
