);
alter table public.practice_question_catalog enable row level security;
revoke all on public.practice_question_catalog from public, anon, authenticated;
grant select on public.practice_question_catalog to authenticated;
create policy "owner reads published question references" on public.practice_question_catalog
for select to authenticated using ((select private.is_learning_owner()));

