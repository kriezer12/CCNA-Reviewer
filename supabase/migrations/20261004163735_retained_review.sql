-- Trusted operator configuration, not writable from the Data API. Register the
-- existing owner UUID/email during an authorized release; deny by default.
create table private.learning_owner (
  singleton boolean primary key default true check (singleton),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  email text not null check (email = lower(btrim(email)) and length(email) > 0)
);
alter table private.learning_owner enable row level security;
revoke all on private.learning_owner from public, anon, authenticated;

create function private.is_learning_owner() returns boolean
language sql stable security definer set search_path = ''
as $$
  select auth.uid() is not null
    and coalesce(auth.jwt()->>'exp', '') ~ '^[0-9]+$'
    and case when coalesce(auth.jwt()->>'exp', '') ~ '^[0-9]+$'
      then (auth.jwt()->>'exp')::numeric > extract(epoch from now()) else false end
    and exists (select 1 from private.learning_owner o
      where o.user_id = auth.uid()
        and o.email = lower(btrim(auth.jwt()->>'email')));
$$;
revoke all on function private.is_learning_owner() from public, anon, authenticated;
grant execute on function private.is_learning_owner() to authenticated;

