using ((select private.is_learning_owner()) and user_id = (select auth.uid()));
create policy "owner saves review" on public.review_items for insert to authenticated
with check ((select private.is_learning_owner()) and user_id = (select auth.uid()));
create policy "owner removes review" on public.review_items for delete to authenticated
using ((select private.is_learning_owner()) and user_id = (select auth.uid()));
